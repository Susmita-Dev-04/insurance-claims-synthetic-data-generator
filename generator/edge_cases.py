
"""
Step 7 - Inject labelled edge cases into a clean insurance claims dataset.

Input:
    data/                 Clean baseline generated by generator.transactions

Output:
    data_edge_cases/      Dataset with deliberate anomalies
    data_edge_cases/ground_truth.csv

Run:
    python -m generator.edge_cases --data data --out data_edge_cases

IMPORTANT:
    This script intentionally modifies source records. The independent audit
    should detect the injected inconsistencies. Do not expect zero mismatches
    after injection.
"""

import argparse
import csv
import os
import shutil
from collections import Counter, defaultdict
from datetime import date, timedelta

from generator import ids
from generator import rules as R


TABLES = [
    "customer",
    "coverage",
    "policy",
    "policy_coverage",
    "adjuster",
    "incident",
    "claim",
    "claim_item",
    "document",
    "claim_assignment",
    "assessment",
    "assessment_check",
    "reserve",
    "settlement",
    "claim_status_event",
]

GROUND_TRUTH_COLUMNS = [
    "edge_case_id",
    "claim_id",
    "anomaly_type",
    "table_name",
    "record_id",
    "description",
    "expected_rule",
    "expected_outcome",
]


def read_csv(path):
    """Read a CSV as dictionaries, preserving values as strings."""
    with open(path, "r", newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def write_csv(path, rows):
    """Write dictionaries using the original column order."""
    if not rows:
        return

    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)

    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def parse_date(value):
    if not value:
        return None
    return date.fromisoformat(value)


def money(value):
    if value in (None, ""):
        return 0.0
    return float(value)


def date_string(value):
    return value.isoformat() if value else ""


def load_dataset(data_dir):
    tables = {}

    for name in TABLES:
        path = os.path.join(data_dir, f"{name}.csv")
        if not os.path.isfile(path):
            raise FileNotFoundError(
                f"Missing required file: {path}\n"
                "Generate the clean baseline first."
            )
        tables[name] = read_csv(path)

    return tables


def index_by(rows, key):
    return {row[key]: row for row in rows}


def add_ground_truth(
    ground_truth,
    case_id,
    claim_id,
    anomaly_type,
    table_name,
    record_id,
    description,
    expected_rule,
    expected_outcome,
):
    ground_truth.append({
        "edge_case_id": case_id,
        "claim_id": claim_id,
        "anomaly_type": anomaly_type,
        "table_name": table_name,
        "record_id": record_id,
        "description": description,
        "expected_rule": expected_rule,
        "expected_outcome": expected_outcome,
    })


def build_context(tables):
    policies = index_by(tables["policy"], "policy_id")
    incidents = index_by(tables["incident"], "incident_id")
    claims = index_by(tables["claim"], "claim_id")
    assessments = index_by(tables["assessment"], "claim_id")

    items_by_claim = defaultdict(list)
    docs_by_claim = defaultdict(list)
    settlements_by_claim = defaultdict(list)
    claims_by_policy = defaultdict(list)
    claims_by_customer = defaultdict(list)
    policy_coverages = {}

    for row in tables["claim_item"]:
        items_by_claim[row["claim_id"]].append(row)

    for row in tables["document"]:
        docs_by_claim[row["claim_id"]].append(row)

    for row in tables["settlement"]:
        settlements_by_claim[row["claim_id"]].append(row)

    for claim in tables["claim"]:
        claims_by_policy[claim["policy_id"]].append(claim)

        policy = policies[claim["policy_id"]]
        claims_by_customer[policy["customer_id"]].append(claim)

    for row in tables["policy_coverage"]:
        policy_coverages[
            (row["policy_id"], row["coverage_id"])
        ] = row

    coverage_by_id = index_by(tables["coverage"], "coverage_id")

    return {
        "policies": policies,
        "incidents": incidents,
        "claims": claims,
        "assessments": assessments,
        "items_by_claim": items_by_claim,
        "docs_by_claim": docs_by_claim,
        "settlements_by_claim": settlements_by_claim,
        "claims_by_policy": claims_by_policy,
        "claims_by_customer": claims_by_customer,
        "policy_coverages": policy_coverages,
        "coverage_by_id": coverage_by_id,
    }


def is_clean_eligible(claim, ctx):
    """Prefer baseline claims assessed as ELIGIBLE / R01_OK."""
    assessment = ctx["assessments"].get(claim["claim_id"])

    if not assessment:
        return False

    if assessment["eligibility"] != "ELIGIBLE":
        return False

    if assessment["reason_code"] != R.R01:
        return False

    return True


def claim_limit(claim, ctx):
    """Get the applicable coverage limit for a claim's item."""
    items = ctx["items_by_claim"].get(claim["claim_id"], [])

    if len({item["coverage_id"] for item in items}) != 1:
        return None

    coverage_id = items[0]["coverage_id"]
    pc = ctx["policy_coverages"].get(
        (claim["policy_id"], coverage_id)
    )

    if pc is None:
        return None

    return money(pc["coverage_limit"])


def get_available_claims(tables, ctx, used_claim_ids):
    return [
        claim
        for claim in sorted(
            tables["claim"], key=lambda row: row["claim_id"]
        )
        if claim["claim_id"] not in used_claim_ids
        and is_clean_eligible(claim, ctx)
    ]


def choose_claim(candidates, description):
    if not candidates:
        raise RuntimeError(
            f"Cannot inject edge case: no suitable claim found for "
            f"{description}.\n"
            "Try regenerating the clean baseline with more claims."
        )

    return candidates[0]


def find_doc_to_remove(claim, ctx):
    """Find a mandatory document received by the assessment date."""
    assessment = ctx["assessments"][claim["claim_id"]]
    assessed_date = parse_date(assessment["assessed_date"])
    incident = ctx["incidents"][claim["incident_id"]]

    required = R.mandatory_docs(
        claim["claim_type"],
        incident["incident_type"],
    )

    for doc in ctx["docs_by_claim"].get(claim["claim_id"], []):
        if doc["is_mandatory"] != "TRUE":
            continue

        if doc["doc_type"] not in required:
            continue

        received = parse_date(doc["received_date"])

        if received is not None and received <= assessed_date:
            return doc

    return None


def inject_edge_cases(tables):
    ctx = build_context(tables)
    ground_truth = []
    used_claim_ids = set()

    # ---------------------------------------------------------------
    # EDGE-001: Claim filed before policy start.
    # Avoid changing claim-history counts for other claims belonging
    # to the same customer.
    # ---------------------------------------------------------------
    eligible = get_available_claims(
        tables, ctx, used_claim_ids
    )

    candidates = []
    for claim in eligible:
        policy = ctx["policies"][claim["policy_id"]]
        customer_claims = ctx["claims_by_customer"][
            policy["customer_id"]
        ]

        if len(customer_claims) == 1:
            candidates.append(claim)

    claim = choose_claim(candidates, "claim date before policy start")
    policy = ctx["policies"][claim["policy_id"]]
    old_claim_date = parse_date(claim["claim_date"])

    claim["claim_date"] = date_string(
        parse_date(policy["start_date"]) - timedelta(days=1)
    )

    used_claim_ids.add(claim["claim_id"])

    add_ground_truth(
        ground_truth,
        "EDGE-001",
        claim["claim_id"],
        "CLAIM_DATE_BEFORE_POLICY_START",
        "claim",
        claim["claim_id"],
        f"Claim date changed from {old_claim_date} to one day "
        f"before policy start ({policy['start_date']}).",
        "CHK01 / R10_CLAIM_BEFORE_POLICY_START",
        "NOT_ELIGIBLE",
    )

    # ---------------------------------------------------------------
    # EDGE-002: Policy cancelled before the incident.
    # Choose a policy with only one claim so other claims are not
    # affected by changing a shared policy record.
    # ---------------------------------------------------------------
    eligible = get_available_claims(
        tables, ctx, used_claim_ids
    )

    candidates = []
    for c in eligible:
        if len(ctx["claims_by_policy"][c["policy_id"]]) != 1:
            continue

        incident = ctx["incidents"][c["incident_id"]]
        policy = ctx["policies"][c["policy_id"]]
        incident_day = parse_date(incident["incident_date"])

        if incident_day > parse_date(policy["start_date"]):
            if incident_day <= parse_date(policy["end_date"]):
                candidates.append(c)

    claim = choose_claim(
        candidates, "policy cancelled before incident"
    )
    incident = ctx["incidents"][claim["incident_id"]]
    policy = ctx["policies"][claim["policy_id"]]
    incident_day = parse_date(incident["incident_date"])

    policy["cancelled_date"] = date_string(
        incident_day - timedelta(days=1)
    )

    used_claim_ids.add(claim["claim_id"])

    add_ground_truth(
        ground_truth,
        "EDGE-002",
        claim["claim_id"],
        "POLICY_CANCELLED_BEFORE_INCIDENT",
        "policy",
        policy["policy_id"],
        f"Cancellation date set to {policy['cancelled_date']}, "
        f"one day before incident {incident_day}.",
        "CHK03 / R04_CANCELLED_BEFORE_INCIDENT",
        "NOT_ELIGIBLE",
    )

    # ---------------------------------------------------------------
    # EDGE-003: Duplicate claim.
    # Reuse a later claim under the same policy and make its incident
    # key match an earlier claim. IDs remain in the correct format.
    # ---------------------------------------------------------------
    eligible = get_available_claims(
        tables, ctx, used_claim_ids
    )

    duplicate_pair = None
    sorted_claims = sorted(
        tables["claim"], key=lambda row: row["claim_id"]
    )

    for target in eligible:
        if target["claim_id"] in used_claim_ids:
            continue

        target_incident = ctx["incidents"][target["incident_id"]]
        target_items = ctx["items_by_claim"][target["claim_id"]]

        if len({x["coverage_id"] for x in target_items}) != 1:
            continue

        coverage_id = target_items[0]["coverage_id"]
        pc = ctx["policy_coverages"].get(
            (target["policy_id"], coverage_id)
        )

        if not pc:
            continue

        coverage = ctx["coverage_by_id"][coverage_id]

        for earlier in sorted_claims:
            if earlier["claim_id"] >= target["claim_id"]:
                break

            if earlier["claim_id"] == target["claim_id"]:
                continue

            if earlier["policy_id"] != target["policy_id"]:
                continue

            earlier_incident = ctx["incidents"][earlier["incident_id"]]

            # Keep the changed incident type covered by this target's
            # existing coverage so CHK05 is the relevant failure.
            if not R.covers(
                coverage["exclusions"],
                earlier_incident["incident_type"],
            ):
                continue

            if (
                earlier_incident["incident_type"]
                == target_incident["incident_type"]
                and earlier_incident["incident_date"]
                == target_incident["incident_date"]
            ):
                continue

            duplicate_pair = (target, earlier, earlier_incident)
            break

        if duplicate_pair:
            break

    if not duplicate_pair:
        raise RuntimeError(
            "Cannot inject EDGE-003: no suitable same-policy claim "
            "pair found. Regenerate with more claims."
        )

    target, earlier, earlier_incident = duplicate_pair
    target_incident = ctx["incidents"][target["incident_id"]]

    target_incident["incident_type"] = earlier_incident["incident_type"]
    target_incident["incident_date"] = earlier_incident["incident_date"]

    used_claim_ids.add(target["claim_id"])

    add_ground_truth(
        ground_truth,
        "EDGE-003",
        target["claim_id"],
        "DUPLICATE_CLAIM",
        "incident",
        target_incident["incident_id"],
        f"Incident key changed to match earlier claim "
        f"{earlier['claim_id']} under the same policy.",
        "CHK05 / R06_DUPLICATE_CLAIM",
        "NOT_ELIGIBLE",
    )

    # ---------------------------------------------------------------
    # EDGE-004: Settlement exceeds coverage limit.
    # Money values in CSV are rupees, not cents.
    # ---------------------------------------------------------------
    eligible = get_available_claims(
        tables, ctx, used_claim_ids
    )

    candidates = [
        c for c in eligible
        if ctx["settlements_by_claim"].get(c["claim_id"])
        and claim_limit(c, ctx) is not None
    ]

    claim = choose_claim(candidates, "settlement above coverage limit")
    settlement = ctx["settlements_by_claim"][claim["claim_id"]][0]
    limit = claim_limit(claim, ctx)

    settlement["settlement_amount"] = f"{limit + 100:.2f}"

    used_claim_ids.add(claim["claim_id"])

    add_ground_truth(
        ground_truth,
        "EDGE-004",
        claim["claim_id"],
        "SETTLEMENT_EXCEEDS_LIMIT",
        "settlement",
        settlement["settlement_id"],
        f"Settlement amount set to ₹{limit + 100:.2f}, "
        f"which is ₹100 above the coverage limit of ₹{limit:.2f}.",
        "Settlement amount must not exceed coverage limit",
        "FLAG_SETTLEMENT_OVER_LIMIT",
    )

    # ---------------------------------------------------------------
    # EDGE-005: Remove a mandatory document.
    # ---------------------------------------------------------------
    eligible = get_available_claims(
        tables, ctx, used_claim_ids
    )

    doc_candidate = None
    for c in eligible:
        doc = find_doc_to_remove(c, ctx)
        if doc is not None:
            doc_candidate = (c, doc)
            break

    if not doc_candidate:
        raise RuntimeError(
            "Cannot inject EDGE-005: no eligible claim has a received "
            "mandatory document. Regenerate with more claims."
        )

    claim, doc = doc_candidate
    tables["document"].remove(doc)
    used_claim_ids.add(claim["claim_id"])

    add_ground_truth(
        ground_truth,
        "EDGE-005",
        claim["claim_id"],
        "MISSING_MANDATORY_DOCUMENT",
        "document",
        doc["document_id"],
        f"Mandatory document {doc['doc_type']} was removed.",
        "CHK04 / R05_MISSING_MANDATORY_DOC",
        "NOT_ELIGIBLE",
    )

    # ---------------------------------------------------------------
    # EDGE-006: A paid settlement is duplicated.
    # Use the project's settlement ID helper.
    # ---------------------------------------------------------------
    eligible = get_available_claims(
        tables, ctx, used_claim_ids
    )

    candidates = []
    for c in eligible:
        for s in ctx["settlements_by_claim"].get(c["claim_id"], []):
            if s["status"] == "PAID":
                candidates.append(c)
                break

    claim = choose_claim(candidates, "duplicate paid settlement")
    original = ctx["settlements_by_claim"][claim["claim_id"]][0]

    existing_ids = [
        row["settlement_id"]
        for row in tables["settlement"]
        if row["claim_id"] == claim["claim_id"]
    ]
    next_number = len(existing_ids) + 1

    duplicate = dict(original)
    duplicate["settlement_id"] = ids.settlement_id(
        claim["claim_id"], next_number
    )
    tables["settlement"].append(duplicate)

    used_claim_ids.add(claim["claim_id"])

    add_ground_truth(
        ground_truth,
        "EDGE-006",
        claim["claim_id"],
        "CLAIM_PAID_TWICE",
        "settlement",
        duplicate["settlement_id"],
        f"Duplicated paid settlement {original['settlement_id']}; "
        f"claim now has more than one settlement record.",
        "Exactly one settlement per payable claim",
        "FLAG_DUPLICATE_SETTLEMENT",
    )

    # ---------------------------------------------------------------
    # EDGE-007: Fraud score crosses the manual-review threshold.
    # Select a new-policy, near-limit claim; setting report delay to
    # 15 days adds the late-report flag.
    # ---------------------------------------------------------------
    eligible = get_available_claims(
        tables, ctx, used_claim_ids
    )

    candidates = []
    for c in eligible:
        incident = ctx["incidents"][c["incident_id"]]
        policy = ctx["policies"][c["policy_id"]]
        limit = claim_limit(c, ctx)

        if limit is None or limit <= 0:
            continue

        incident_day = parse_date(incident["incident_date"])
        start_day = parse_date(policy["start_date"])
        claimed = money(c["claimed_amount"])

        if (incident_day - start_day).days > 30:
            continue

        if claimed < 0.90 * limit:
            continue

        # Keep the resulting reported date within the dataset as-of
        # period and do not move the claim to an earlier report date.
        reported_day = incident_day + timedelta(days=15)
        if reported_day > date.today() + timedelta(days=365):
            continue

        candidates.append(c)

    claim = choose_claim(
        candidates, "fraud review from late reporting and near-limit amount"
    )
    incident = ctx["incidents"][claim["incident_id"]]
    incident_day = parse_date(incident["incident_date"])
    new_report_date = incident_day + timedelta(days=15)

    incident["reported_date"] = date_string(new_report_date)

    used_claim_ids.add(claim["claim_id"])

    add_ground_truth(
        ground_truth,
        "EDGE-007",
        claim["claim_id"],
        "FRAUD_INDICATOR",
        "incident",
        incident["incident_id"],
        "Reported date set to 15 days after the incident. Together with "
        "the new-policy and near-limit indicators, this should trigger "
        "manual fraud review.",
        "CHK07 / R09_FRAUD_REVIEW",
        "REFER_MANUAL",
    )

    # ---------------------------------------------------------------
    # EDGE-008: Mandatory document arrives after assessment.
    # ---------------------------------------------------------------
    eligible = get_available_claims(
        tables, ctx, used_claim_ids
    )

    doc_candidate = None
    for c in eligible:
        doc = find_doc_to_remove(c, ctx)
        if doc is not None:
            doc_candidate = (c, doc)
            break

    if not doc_candidate:
        raise RuntimeError(
            "Cannot inject EDGE-008: no suitable mandatory document "
            "found. Regenerate with more claims."
        )

    claim, doc = doc_candidate
    assessment = ctx["assessments"][claim["claim_id"]]
    assessed_day = parse_date(assessment["assessed_date"])
    doc["received_date"] = date_string(
        assessed_day + timedelta(days=1)
    )
    doc["status"] = "PENDING"

    used_claim_ids.add(claim["claim_id"])

    add_ground_truth(
        ground_truth,
        "EDGE-008",
        claim["claim_id"],
        "INCOMPLETE_EVIDENCE",
        "document",
        doc["document_id"],
        f"Mandatory document {doc['doc_type']} is now received one day "
        f"after assessment date {assessed_day}.",
        "CHK04 / R05_MISSING_MANDATORY_DOC",
        "NOT_ELIGIBLE",
    )

    return tables, ground_truth


def main():
    parser = argparse.ArgumentParser(
        description="Inject labelled anomalies into insurance claims data."
    )
    parser.add_argument(
        "--data",
        default="data",
        help="Directory containing the clean baseline CSV files.",
    )
    parser.add_argument(
        "--out",
        default="data_edge_cases",
        help="Output directory for the anomaly dataset and ground truth.",
    )
    args = parser.parse_args()

    if os.path.abspath(args.data) == os.path.abspath(args.out):
        raise ValueError(
            "--data and --out must be different directories. "
            "Keep the clean baseline unchanged."
        )

    tables = load_dataset(args.data)

    # Keep unrelated CSV files from the input directory, if any.
    os.makedirs(args.out, exist_ok=True)
    for filename in os.listdir(args.data):
        source = os.path.join(args.data, filename)
        destination = os.path.join(args.out, filename)

        if (
            filename.endswith(".csv")
            and filename not in {f"{name}.csv" for name in TABLES}
            and os.path.isfile(source)
        ):
            shutil.copy2(source, destination)

    tables, ground_truth = inject_edge_cases(tables)

    for name in TABLES:
        write_csv(os.path.join(args.out, f"{name}.csv"), tables[name])

    ground_truth_path = os.path.join(args.out, "ground_truth.csv")
    with open(
        ground_truth_path, "w", newline="", encoding="utf-8"
    ) as f:
        writer = csv.DictWriter(f, fieldnames=GROUND_TRUTH_COLUMNS)
        writer.writeheader()
        writer.writerows(ground_truth)

    print(f"Edge-case dataset written to: {args.out}")
    print(f"Ground truth written to: {ground_truth_path}")
    print(f"Injected edge cases: {len(ground_truth)}")

    for row in ground_truth:
        print(
            f"  {row['edge_case_id']}: "
            f"{row['anomaly_type']} -> {row['claim_id']}"
        )


if __name__ == "__main__":
    main()
